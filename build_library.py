#!/usr/bin/env python3
"""
build_library.py — SEO, analytics and chrome for frameworks.dianasimpsonhernandez.com

    python3 build_library.py          # inject head tags + analytics into every page, write sitemap/robots/404
    python3 build_library.py --og     # also render 1200×630 preview cards for pages that have none

Idempotent: everything injected sits between <!--dsh:head--> … <!--dsh:/head--> markers and is
replaced on each run, so legacy pages keep their own CSS/JS untouched. New pages (lever, recall,
stake, case study) are generated by their own modules in pages/ and then treated like any other.
Page metadata comes from data/frameworks.json (listed) and META below (unlisted).
"""
