def build_og(pages, force=False):
    from playwright.sync_api import sync_playwright
    import base64
    fdir = os.path.join(ROOT, "assets", "fonts")
    b64 = lambda n: base64.b64encode(open(os.path.join(fdir, n), "rb").read()).decode()
    with sync_playwright() as pw:
        b = pw.chromium.launch(); pg = b.new_page(viewport={"width": 1200, "height": 630})
        for slug, path, fw in pages:
            out = os.path.join(ROOT, "assets", f"preview-{'library' if slug=='index' else slug}.png")
            if os.path.exists(out) and not force: continue
            m = page_meta(slug, fw)
            if m.get("noindex"): continue
            title = fw["title"] if fw else m["name"]; sub = fw["subtitle"] if fw else m["description"]
            cat = (fw["category"] if fw else "Library").upper()
            size = 104 if len(title) < 16 else 84 if len(title) < 26 else 64
            html = OG.replace("__SG__", b64("SchibstedGrotesk-var.woff2")).replace("__MM__", b64("MartianMono-var.woff2")).replace("__TITLE__", H.escape(title)).replace("__SUB__", H.escape(sub)).replace("__CAT__", H.escape(cat)).replace("__SIZE__", str(size))
            pg.set_content(html, wait_until="load"); pg.evaluate("document.fonts.ready"); pg.wait_for_timeout(200)
            pg.screenshot(path=out, type="png"); print(f"  ✓ {os.path.relpath(out, ROOT)}")
        b.close()

