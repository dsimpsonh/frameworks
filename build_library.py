def load_frameworks():
    with open(os.path.join(ROOT, "data", "frameworks.json"), encoding="utf-8") as f:
        return json.load(f)["frameworks"]

def page_meta(slug: str, fw: dict | None):
    if fw:
        return {"title": f"{fw['title']} — {fw['subtitle']}", "description": fw["summary"], "type": "article",
                "noindex": False, "category": fw["category"], "name": fw["title"], "extra_css": META.get(slug, {}).get("extra_css", "")}
    m = dict(META.get(slug, {"title": slug, "description": ""}))
    m.setdefault("type", "article"); m.setdefault("noindex", False); m.setdefault("name", m["title"].split(" — ")[0])
    return m

def jsonld(slug, m, url):
    person = {"@type": "Person", "name": "Diana Simpson-Hernandez", "url": MAIN + "/", "sameAs": [MAIN + "/", "https://linkedin.com/in/dianasimpson", "https://www.youtube.com/@DianaSimpsonHernandez"]}
    if slug == "index":
        return {"@context": "https://schema.org", "@type": "CollectionPage", "name": "Open Frameworks", "url": url, "author": person,
                "isPartOf": {"@type": "WebSite", "name": "Diana Simpson-Hernandez", "url": MAIN + "/"}}
    kind = {"Course": "Course", "Case Study": "Article", "Method": "TechArticle"}.get(m.get("category", ""), "CreativeWork")
    d = {"@context": "https://schema.org", "@type": kind, "name": m["name"], "headline": m["title"], "description": m["description"], "url": url,
         "author": person, "publisher": person, "inLanguage": "en", "isAccessibleForFree": True, "dateModified": TODAY}
    if kind == "Course":
        d["provider"] = person; d["offers"] = {"@type": "Offer", "price": "0", "priceCurrency": "GBP", "availability": "https://schema.org/InStock", "url": url}
        d["hasCourseInstance"] = [{"@type": "CourseInstance", "courseMode": "online", "courseWorkload": "PT8H"}]
    return d

def head_block(slug, m, has_preview):
    path = "/" if slug == "index" else f"/{slug}/"
    url = DOMAIN + path
    og = f"{DOMAIN}/assets/preview-{'library' if slug=='index' else slug}.png" if has_preview else f"{DOMAIN}/assets/preview-library.png"
    robots = '<meta name="robots" content="noindex,follow">' if m.get("noindex") else '<meta name="robots" content="index,follow,max-image-preview:large">'
    t = H.escape(m["title"]); d = H.escape(m["description"])
    return f"""<!--dsh:head-->
<meta name="description" content="{d}">
<link rel="canonical" href="{url}">
{robots}
<meta name="author" content="Diana Simpson-Hernandez">
<meta property="og:type" content="{m.get('type','article')}"><meta property="og:site_name" content="Open Frameworks · Diana Simpson-Hernandez"><meta property="og:locale" content="en_GB">
<meta property="og:url" content="{url}"><meta property="og:title" content="{t}"><meta property="og:description" content="{d}">
<meta property="og:image" content="{og}"><meta property="og:image:width" content="1200"><meta property="og:image:height" content="630"><meta property="og:image:alt" content="{t}">
<meta name="twitter:card" content="summary_large_image"><meta name="twitter:title" content="{t}"><meta name="twitter:description" content="{d}"><meta name="twitter:image" content="{og}">
<link rel="sitemap" type="application/xml" href="/sitemap.xml">
{ANALYTICS}
<script type="application/ld+json">{json.dumps(jsonld(slug, m, url), ensure_ascii=False)}</script>
{('<style>'+m['extra_css']+'</style>') if m.get('extra_css') else ''}
<!--dsh:/head-->"""

STRIP = [  # legacy tags the block replaces
    re.compile(r'<meta\s+name="description"[^>]*>\s*', re.I),
    re.compile(r'<meta\s+(?:property|name)="(?:og:|twitter:)[^"]*"[^>]*>\s*', re.I),
    re.compile(r'<link\s+rel="canonical"[^>]*>\s*', re.I),
    re.compile(r'<!--dsh:head-->.*?<!--dsh:/head-->\s*', re.S),
]

def inject(path, slug, m, has_preview):
    s = open(path, encoding="utf-8").read()
    for rx in STRIP: s = rx.sub("", s)
    if not re.search(r"<title>", s, re.I):
        s = re.sub(r"(<head[^>]*>)", r"\1\n<title>" + H.escape(m["title"]) + "</title>", s, count=1, flags=re.I)
    s = re.sub(r"(</head>)", head_block(slug, m, has_preview) + "\n\\1", s, count=1, flags=re.I)
    tmp = path + ".tmp"; open(tmp, "w", encoding="utf-8").write(s); os.replace(tmp, path)
    return len(s)

def all_pages():
    fws = {f["url"].strip("/"): f for f in load_frameworks()}
    out = [("index", os.path.join(ROOT, "index.html"), None)]
    for d in sorted(os.listdir(ROOT)):
        p = os.path.join(ROOT, d, "index.html")
        if os.path.isfile(p) and d not in ("assets", "data", "styles", "pages", "og"):
            out.append((d, p, fws.get(d)))
    return out

def build_404():
    body = f"""<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Not found — Open Frameworks</title><meta name="robots" content="noindex"><link rel="stylesheet" href="/assets/fonts/fonts.css"><link rel="stylesheet" href="/styles/main.css">
{ANALYTICS}
<style>.nf{{min-height:70vh;display:flex;flex-direction:column;justify-content:center;gap:1rem;max-width:60ch}}.nf h1{{font-size:clamp(2.4rem,7vw,5rem);line-height:1;letter-spacing:-.02em}}.nf a{{color:var(--accent);font-weight:600}}</style></head>
<body><div class="container nf"><span class="eyebrow">404</span><h1>That framework moved.</h1><p>The library was rebuilt in September 2026. Everything is still here — start from the index.</p>
<p><a href="/">Browse the library →</a> &nbsp; <a href="{MAIN}/">Main site →</a></p></div></body></html>"""
    open(os.path.join(ROOT, "404.html"), "w", encoding="utf-8").write(body)

def build_sitemap(pages):
    urls = ""
    for slug, path, fw in pages:
        m = page_meta(slug, fw)
        if m.get("noindex"): continue
        loc = DOMAIN + ("/" if slug == "index" else f"/{slug}/")
        urls += f"<url><loc>{loc}</loc><lastmod>{TODAY}</lastmod><changefreq>monthly</changefreq><priority>{'1.0' if slug=='index' else '0.8'}</priority></url>"
    open(os.path.join(ROOT, "sitemap.xml"), "w").write(f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">{urls}</urlset>\n')
    open(os.path.join(ROOT, "robots.txt"), "w").write(f"User-agent: *\nAllow: /\nDisallow: /404.html\nDisallow: /launcher/\nDisallow: /STFC_faq/\n\nSitemap: {DOMAIN}/sitemap.xml\n")

